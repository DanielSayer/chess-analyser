// Regenerates src/core/openings-data.ts from the Lichess opening catalogue
// (CC0, https://github.com/lichess-org/chess-openings). Run manually:
//   node scripts/build-openings.mjs
import { writeFileSync } from 'node:fs'
import { Chess } from 'chess.js'
import { bookKey, hashKey } from '../src/core/book-key.ts'

const SOURCE = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master'
const hashes = new Set()
let lines = 0

for (const volume of ['a', 'b', 'c', 'd', 'e']) {
  const response = await fetch(`${SOURCE}/${volume}.tsv`)
  if (!response.ok) throw new Error(`${volume}.tsv: HTTP ${response.status}`)
  for (const row of (await response.text()).trim().split('\n').slice(1)) {
    const pgn = row.split('\t')[2]
    const chess = new Chess()
    chess.loadPgn(pgn)
    const replay = new Chess()
    for (const move of chess.history()) {
      replay.move(move)
      hashes.add(hashKey(bookKey(replay.fen())))
    }
    lines++
  }
}

const sorted = Uint32Array.from([...hashes].sort((a, b) => a - b))
const base64 = Buffer.from(sorted.buffer).toString('base64')
writeFileSync(new URL('../src/core/openings-data.ts', import.meta.url), `// Generated by scripts/build-openings.mjs. Do not edit.
// Source: Lichess chess-openings (CC0-1.0), ${lines} lines, ${sorted.length} positions.
// Sorted little-endian uint32 position hashes, base64 encoded.
export const BOOK_POSITIONS = '${base64}'
`)
console.log(`${lines} lines, ${sorted.length} book positions`)
